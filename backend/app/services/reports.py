"""Generate a PDF summary for a persisted simulation run."""
from __future__ import annotations

from io import BytesIO
from typing import Any

from matplotlib.backends.backend_pdf import PdfPages
from matplotlib.figure import Figure


def build_run_pdf(record: dict[str, Any]) -> bytes:
    result = record["result"]
    rows = result.get("telemetry", {}).get("event_time_series", [])
    output = BytesIO()
    with PdfPages(output) as pdf:
        page = Figure(figsize=(8.27, 11.69))
        page.text(0.08, 0.94, "FlexProof AI | Simulation Run Report", fontsize=18, weight="bold")
        page.text(0.08, 0.89, f"Scenario: {result.get('scenario_id')}    Run: {result.get('run_id')}", fontsize=9)
        page.text(0.08, 0.865, f"Controller: {result.get('controller')}    Status: {result.get('status')}", fontsize=10)
        page.text(0.08, 0.825, f"Accepted commitment: {result.get('accepted_commitment_mw')} MW", fontsize=12)
        reliability = result.get("reliability") or {}
        page.text(0.08, 0.795,
                  f"Reliability evidence: {reliability.get('status', 'not evaluated')} | "
                  f"estimate={reliability.get('estimate')} | lower bound={reliability.get('confidence_lower_bound')} | "
                  f"split={reliability.get('evidence_split', 'not applicable')}", fontsize=9)
        verify = result.get("independent_verification", {})
        page.text(0.08, 0.765,
                  f"Telemetry arithmetic checks: {verify.get('status', 'not available')} "
                  f"({verify.get('check_count', 0)} checks; certification is not provided)", fontsize=9)
        page.text(0.08, 0.72, "Assumptions", fontsize=12, weight="bold")
        req = record["request"]
        page.text(0.08, 0.69,
                  f"Requested reduction: {req['requested_reduction_mw']} MW\n"
                  f"Event duration: {req['duration_minutes']} minutes\n"
                  f"Reliability target: {req['reliability_target']:.1%}\n"
                  f"Initial battery SoC: {req['battery_soc_percent']:.1f}%\n"
                  f"Random seed: {req['random_seed']}\n"
                  f"Calibration scenarios: {req['calibration_scenarios']}\n"
                  "Simulated outputs only; this report does not certify facility or utility performance.",
                  fontsize=9, linespacing=1.7)
        if rows:
            ax = page.add_axes((0.11, 0.17, 0.82, 0.30))
            times = [row.get("end_minute", i + 1) for i, row in enumerate(rows)]
            ax.plot(times, [row.get("baseline_grid_import_mw") for row in rows],
                    label="Baseline import", color="#64748b")
            ax.plot(times, [row.get("grid_import_mw") for row in rows],
                    label="Grid import", color="#d5a728")
            ax.set_title("Event grid import")
            ax.set_xlabel("Minute")
            ax.set_ylabel("MW")
            ax.grid(alpha=0.25)
            ax.legend()
        page.text(0.08, 0.08, "Generated by the FlexProof AI research prototype.", fontsize=8, color="#475569")
        pdf.savefig(page)
    return output.getvalue()
